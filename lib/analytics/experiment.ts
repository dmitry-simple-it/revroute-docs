'use client'

import { useEffect, useState } from 'react'

/**
 * Минимальный клиентский A/B-сплит для офферов инструментов.
 *
 * Никакой инфраструктуры экспериментов: вариант назначается один раз на
 * браузер (localStorage, 50/50) и уезжает ПАРАМЕТРОМ во все цели моста
 * (tool_upgrade_view / tool_signup_click) — анализ в Метрике фильтром по
 * params.variant. Альтернатива — Вариокуб; он подключён к счётчику, но
 * требует настройки эксперимента в интерфейсе и flags-запросов, для первой
 * итерации это перебор.
 *
 * SSR-мигания нет: до маунта хук отдаёт 'a', но офферы рендерятся только
 * после первого успешного действия пользователя (создание кода/ссылки), к
 * этому моменту эффект давно отработал.
 *
 * ЧЕСТНОЕ ОГРАНИЧЕНИЕ ВЫБОРКИ: при текущем бюджете (~60–95 визитов/нед,
 * ~22–34 показа оффера) разницу вариантов в разы видно за 2–3 недели, а
 * разницу в проценты — месяцы. Сплит — задел под рост бюджета; до тех пор
 * решения принимать по абсолютам (есть клики / нет кликов), не по дельте.
 */
export function useExperimentVariant(experimentId: string): 'a' | 'b' {
  const [variant, setVariant] = useState<'a' | 'b'>('a')

  useEffect(() => {
    const key = `rr_exp_${experimentId}`
    try {
      let v = localStorage.getItem(key)
      if (v !== 'a' && v !== 'b') {
        v = Math.random() < 0.5 ? 'a' : 'b'
        localStorage.setItem(key, v)
      }
      setVariant(v as 'a' | 'b')
    } catch {
      /* приватный режим: остаёмся на 'a', в цели уедет variant=a */
    }
  }, [experimentId])

  return variant
}
